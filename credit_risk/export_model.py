"""Train and export the compact model that the Flask API serves.

The research model (train.py) uses 186 inputs, far too many for a web form. This script keeps the 15 most
important ones, retrains the same LightGBM pipeline on them, picks its decision threshold on the validation
set, evaluates it once on the test set, and writes everything the application needs.

Run from the project root:  python -m credit_risk.export_model
Outputs:
  backend/models/model_bundle.joblib   pipeline + input schema + threshold, loaded by backend/app.py
  data/sample_inputs.csv               two synthetic applicants (not real people), used by the API tests
  frontend/src/app/feature-schema.ts   the same schema for the Angular form (generated, do not edit)
  reports/deploy_model.json            metrics of the deployed model
"""
import json
import platform

import joblib
import lightgbm
import pandas as pd
import sklearn
from sklearn.model_selection import train_test_split

from . import config, data, evaluate, pipeline

# The 15 most important inputs of the full LightGBM model (by gain on the training split), leaving out
# CODE_GENDER because gender is a protected attribute in lending decisions.
# Validation ROC-AUC: all 186 inputs 0.758 | top 10: 0.744 | these 15: 0.750 | top 20: 0.752.
DEPLOY_FEATURES = [
    "EXT_SOURCE_3", "EXT_SOURCE_2", "EXT_SOURCE_1", "DAYS_EMPLOYED", "DAYS_BIRTH",
    "AMT_CREDIT", "AMT_GOODS_PRICE", "AMT_ANNUITY", "NAME_EDUCATION_TYPE", "DAYS_ID_PUBLISH",
    "BUREAU_DAYS_CREDIT_MAX", "BUREAU_AMT_CREDIT_SUM_DEBT_MEAN", "OWN_CAR_AGE",
    "BUREAU_DAYS_CREDIT_ENDDATE_MAX", "BUREAU_AMT_CREDIT_MAX_OVERDUE_SUM",
]

LABELS = {
    "EXT_SOURCE_3": "External credit score 3 (0 to 1)",
    "EXT_SOURCE_2": "External credit score 2 (0 to 1)",
    "EXT_SOURCE_1": "External credit score 1 (0 to 1)",
    "DAYS_EMPLOYED": "Days employed (negative; 365243 = not employed)",
    "DAYS_BIRTH": "Age in days (negative, e.g. -12000 = 33 years)",
    "AMT_CREDIT": "Loan amount",
    "AMT_GOODS_PRICE": "Price of the goods financed",
    "AMT_ANNUITY": "Loan annuity (regular payment)",
    "NAME_EDUCATION_TYPE": "Education level",
    "DAYS_ID_PUBLISH": "Days since ID document was issued (negative)",
    "BUREAU_DAYS_CREDIT_MAX": "Days since newest credit-bureau loan was opened (negative)",
    "BUREAU_AMT_CREDIT_SUM_DEBT_MEAN": "Average current debt per credit-bureau loan",
    "OWN_CAR_AGE": "Age of own car in years (blank if no car)",
    "BUREAU_DAYS_CREDIT_ENDDATE_MAX": "Days until latest credit-bureau loan ends",
    "BUREAU_AMT_CREDIT_MAX_OVERDUE_SUM": "Total of maximum overdue amounts on credit-bureau loans",
}

BUNDLE_FILE = config.ROOT / "backend" / "models" / "model_bundle.joblib"
SAMPLE_FILE = config.ROOT / "data" / "sample_inputs.csv"
SCHEMA_FILE = config.ROOT / "frontend" / "src" / "app" / "feature-schema.ts"
REPORT_FILE = config.REPORTS_DIR / "deploy_model.json"


def build_schema(X):
    """Name, type, allowed values and whether each input may be left blank, all taken from the training split."""
    schema = []
    for name in DEPLOY_FEATURES:
        col = X[name]
        # Inputs that are often missing in real applications (no car, no bureau history) may stay blank.
        field = {"name": name, "label": LABELS[name], "required": bool(col.isna().mean() < 0.01)}
        if pd.api.types.is_numeric_dtype(col):
            field.update(kind="number", min=float(col.min()), max=float(col.max()))
        else:
            field.update(kind="category", options=sorted(col.dropna().unique().tolist()))
        schema.append(field)
    return schema


def synthetic_applicant(X):
    """Median of each numeric input and the most common category: a profile, not a real person's record."""
    return {
        f: round(float(X[f].median()), 4) if pd.api.types.is_numeric_dtype(X[f]) else X[f].mode()[0]
        for f in DEPLOY_FEATURES
    }


def write_frontend_schema(schema, samples, info):
    header = "// GENERATED by `python -m credit_risk.export_model` from the saved model. Do not edit by hand.\n\n"
    body = (
        "export type Feature = {\n  name: string;\n  label: string;\n  kind: 'number' | 'category';\n"
        "  required: boolean;\n  options?: string[];\n  min?: number;\n  max?: number;\n};\n\n"
        "export type Sample = { name: string; values: Record<string, string | number> };\n\n"
        f"export const FEATURES: Feature[] = {json.dumps(schema, indent=2)};\n\n"
        f"export const SAMPLES: Sample[] = {json.dumps(samples, indent=2)};\n\n"
        f"export const MODEL_INFO = {json.dumps(info, indent=2)};\n"
    )
    SCHEMA_FILE.write_text(header + body, encoding="utf-8")


def main():
    seed = config.RANDOM_STATE
    print("Building the applicant table")
    table = data.build_applicant_table(data.load_csv(config.APPLICATION_FILE), data.load_csv(config.BUREAU_FILE))
    X, y = table[DEPLOY_FEATURES], table[config.TARGET]

    # Exactly the same split as train.py, so the test set is still unseen.
    X_rest, X_test, y_rest, y_test = train_test_split(X, y, test_size=config.TEST_SIZE, stratify=y, random_state=seed)
    X_train, X_val, y_train, y_val = train_test_split(
        X_rest, y_rest, test_size=config.VAL_SIZE, stratify=y_rest, random_state=seed
    )

    print(f"Training LightGBM on {len(DEPLOY_FEATURES)} inputs")
    pipe = pipeline.build_pipeline(pipeline.build_models()["lightgbm"]).fit(X_train, y_train)
    threshold = evaluate.pick_threshold(y_val, pipe.predict_proba(X_val)[:, 1])
    test_prob = pipe.predict_proba(X_test)[:, 1]
    metrics = {**evaluate.ranking_scores(y_test, test_prob), **evaluate.score(y_test, test_prob, threshold)}
    print(f"  test ROC-AUC {metrics['roc_auc']:.4f} | recall {metrics['recall']:.1%} at threshold {threshold:.3f}")

    schema = build_schema(X_train)
    samples = [
        {"name": "Typical applicant", "values": synthetic_applicant(X_train)},
        {"name": "Higher-risk profile", "values": synthetic_applicant(X_train[y_train == 1])},
    ]
    sample_frame = pd.DataFrame([s["values"] for s in samples], columns=DEPLOY_FEATURES)
    sample_probs = pipe.predict_proba(sample_frame)[:, 1]
    for sample, prob in zip(samples, sample_probs):
        print(f"  {sample['name']}: probability of default {prob:.3f}")

    BUNDLE_FILE.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(
        {
            "pipeline": pipe,
            "features": DEPLOY_FEATURES,
            "task": "classification",
            "model_version": "1.0",
            "threshold": threshold,
            "schema": schema,
            "metrics": metrics,
            # Known answer for the first sample row, so the backend can check it loads the model correctly.
            "reference": {"sample": samples[0]["name"], "probability": float(sample_probs[0])},
            "trained_with": {"python": platform.python_version(), "scikit-learn": sklearn.__version__,
                             "lightgbm": lightgbm.__version__},
        },
        BUNDLE_FILE,
        compress=3,
    )
    SAMPLE_FILE.parent.mkdir(exist_ok=True)
    sample_frame.to_csv(SAMPLE_FILE, index=False)

    info = {"name": "LightGBM", "version": "1.0", "inputs": len(DEPLOY_FEATURES),
            "rocAuc": round(metrics["roc_auc"], 3), "threshold": round(threshold, 3)}
    if SCHEMA_FILE.parent.exists():
        write_frontend_schema(schema, samples, info)
    else:
        print("  frontend/ not generated yet; skipped feature-schema.ts")

    REPORT_FILE.write_text(json.dumps({"features": DEPLOY_FEATURES, "threshold": threshold, "test": metrics,
                                       "schema": schema}, indent=2))
    for path in (BUNDLE_FILE, SAMPLE_FILE, SCHEMA_FILE, REPORT_FILE):
        if path.exists():
            print(f"  wrote {path.relative_to(config.ROOT)}")


if __name__ == "__main__":
    main()
